import type { CelestialBodyDef, StarSystemDef, Vec3d } from './types';

/**
 * 1 Light-Year in universe double-precision coordinates.
 * Inner Solar System spans ~45,000 units; Alpha Centauri sits at 4.37 * 2,500,000 = 10,925,000 units,
 * giving true 3D galactic parallax and dramatic multi-second superluminal warp voyages!
 */
export const LY_UNITS = 2_500_000;

/**
 * 1 Astronomical Unit (Earth-Sun distance) in scene units.
 */
export const AU_UNITS = 7_480;

/**
 * Convert real equatorial Right Ascension (hours), Declination (deg), and distance (ly)
 * into 3D galactic/equatorial universe coordinates.
 */
function raDecToVec3(raHours: number, decDeg: number, distLy: number): Vec3d {
  const ra = (raHours / 24) * Math.PI * 2;
  const dec = (decDeg * Math.PI) / 180;
  const r = distLy * LY_UNITS;
  return {
    x: r * Math.cos(dec) * Math.cos(ra),
    y: r * Math.sin(dec),
    z: r * Math.cos(dec) * Math.sin(ra),
  };
}

