// against the Voyager while preserving exact non-overlapping orbital clearances.
for (const body of CELESTIAL_BODIES) {
  const isSgrSystem = body.systemId === 'sagittarius-a';
  const radiusMult =
    body.kind === 'black-hole' ? 2.9 : body.kind === 'star' ? 2.55 : 2.2;
  const orbitMult = isSgrSystem ? 2.9 : 2.2;
  body.radius = Math.round(body.radius * radiusMult);
  body.orbitRadius = Math.round(body.orbitRadius * orbitMult);

  if (body.parentId && body.orbitRadius > 0) {
    const preset = KEPLERIAN_ELEMENTS[body.id];
    if (preset) {
      body.orbitEccentricity = preset[0];
      body.argOfPeriapsis = preset[1];
      body.ascendingNode = preset[2];
    } else {
      // Deterministic gentle Keplerian eccentricity & orientation for remaining charted worlds
      const s = Math.abs(Math.sin(body.seed * 12.9898) * 43758.5453) % 1;
      const s2 = Math.abs(Math.sin(body.seed * 78.233) * 24634.6345) % 1;
      const s3 = Math.abs(Math.sin(body.seed * 39.425) * 19283.7465) % 1;
      body.orbitEccentricity = Number((0.018 + s * 0.14).toFixed(4));
      body.argOfPeriapsis = Number((s2 * Math.PI * 2).toFixed(4));
      body.ascendingNode = Number((s3 * Math.PI * 2).toFixed(4));
    }
  } else {
    body.orbitEccentricity = 0;
    body.argOfPeriapsis = 0;
    body.ascendingNode = 0;
  }
}

